"""Stage 10: build RESULTS.md + LaTeX fragments index. Thin CLI wrapper."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import load_config
from src.utils.io import Manifest, atomic_write_text
from src.utils.logging import get_logger, print_summary_block
from src.utils.seeds import seed_everything


def read_csv_safe(path: Path) -> pd.DataFrame | None:
    """Return the CSV as a frame, or None when the stage never ran."""
    return pd.read_csv(path) if path.exists() else None


def main() -> None:
    parser = argparse.ArgumentParser(description="10: build report")
    parser.add_argument("--config", required=True)
    args = parser.parse_args()
    cfg = load_config(args.config)
    seed_everything(cfg.seed)
    log = get_logger("10_build_report", cfg.outputs.logs_dir)
    manifest = Manifest(cfg.outputs.manifest)

    tables = Path(cfg.outputs.tables_dir)
    prefix = "synthetic_" if cfg.data.synthetic else ""
    rows_run = {r["stage"]: r["status"] for r in manifest.read_all()}

    def status_of(stage: str) -> str:
        return rows_run.get(stage, "NOT_RUN")

    desc = read_csv_safe(tables / f"{prefix}table1_descriptive.csv")
    stats_path = tables / f"{prefix}table_stats_tests.json"
    stats = json.loads(stats_path.read_text()) if stats_path.exists() else None
    curve = read_csv_safe(tables / f"{prefix}table2_prefix_auroc.csv")
    heat = read_csv_safe(tables / "table3_probe_heatmap.csv")
    lead = read_csv_safe(tables / f"{prefix}table_lead_summary.csv")
    policy = read_csv_safe(tables / f"{prefix}table_intervention.csv")

    lines = [
        "# Results",
        "",
        (
            "> Auto-generated by `scripts/10_build_report.py`. Every number below "
            "was computed at runtime from data. Stages that never ran (no GPU, "
            "no network) read `NOT_RUN` - never a guessed value."
        ),
        "",
    ]
    if cfg.data.synthetic:
        lines += [
            (
                "> **SMOKE-TEST BUILD**: all numbers below come from labelled "
                "SYNTHETIC data (`configs/quick.yaml`). Do not paste into the paper."
            ),
            "",
        ]
    # Headline numbers.
    if desc is not None and "ALL" in desc["subset"].values:
        all_row = desc.set_index("subset").loc["ALL"]
        lines += ["## Headline numbers", "",
                  f"- Traces analysed: {int(all_row['n_traces'])}",
                  f"- Erroneous: {all_row['pct_erroneous']:.1f}%",
                  f"- Median steps/trace: {all_row['median_steps']:.0f}",
                  (
                      f"- Mean relative onset rho: {all_row['mean_relative_onset']:.3f} "
                      f"[{all_row['relative_onset_ci_lo']:.3f}, "
                      f"{all_row['relative_onset_ci_hi']:.3f}]"
                  ),
                  f"- Mean steps remaining: {all_row['mean_steps_remaining']:.2f}", ""]
    else:
        lines += ["## Headline numbers", "", "- NOT_RUN (03_run_eda has no output yet)", ""]
    if stats is not None:
        ks = stats["ks_uniform"]
        lines += ["## Statistical tests (E2)", "",
                  f"- KS vs Uniform(0,1): D={ks['statistic_D']:.4f}, p={ks['p_value']:.3e}",
                  (
                      f"- Mann-Whitney length: "
                      f"p={stats['mann_whitney_length']['p_value']:.3e}, "
                      f"r={stats['mann_whitney_length']['rank_biserial_r']:+.3f}"
                  ),
                  (
                      f"- Kruskal-Wallis tiers: H={stats['kruskal_tiers']['H']:.3f}, "
                      f"p={stats['kruskal_tiers']['p_value']:.3e}"
                  ), ""]
    else:
        lines += ["## Statistical tests (E2)", "", "- NOT_RUN", ""]
    if curve is not None and not curve.empty:
        lines += ["## Predictability curve (E3)", "",
                  curve.to_markdown(index=False), ""]
    else:
        lines += ["## Predictability curve (E3)", "", "- NOT_RUN", ""]
    if heat is not None and not heat.empty:
        lines += ["## Probe heatmap (E4)", "", heat.to_markdown(index=False), ""]
    else:
        lines += ["## Probe heatmap (E4)", "",
                  (
                      f"- NOT_RUN ({status_of('06_extract_activations')} / "
                      f"{status_of('07_train_probes')})"
                  ), ""]
    if lead is not None and not lead.empty:
        lines += ["## Lead time (E5)", "", lead.to_markdown(index=False), ""]
    else:
        lines += ["## Lead time (E5)", "", "- NOT_RUN", ""]
    if policy is not None and not policy.empty:
        lines += ["## Intervention (E8)", "", policy.to_markdown(index=False), ""]
    else:
        lines += ["## Intervention (E8)", "", "- NOT_RUN", ""]
    # Paper mapping.
    lines += ["## Paper mapping (placeholder -> source)", "",
              "| Placeholder in main.tex | Value source |",
              "|---|---|",
              "| N traces | table1_descriptive.csv, row ALL, n_traces |",
              "| KS D, p | table_stats_tests.json, ks_uniform |",
              "| mean rho, steps remaining | table1_descriptive.csv, row ALL |",
              "| AUROC at 25% / 100% | table2_prefix_auroc.csv, lexical rows |",
              "| surface floor | 05_train_baselines stdout + manifest |",
              "| Kruskal H, p | table_stats_tests.json, kruskal_tiers |",
              "| onset Fig (Fig. 2) | fig4_relative_error_position_HEADLINE.png/pdf |",
              "| predictability Fig (Fig. 3) | fig7_auroc_vs_prefix_KEY.png/pdf |",
              ""]
    lines += ["## Stage status", "",
              "| Stage | Status |",
              "|---|---|"]
    for stage in ("01_download_data", "02_preprocess", "03_run_eda",
                  "04_run_statistics", "05_train_baselines",
                  "06_extract_activations", "07_train_probes",
                  "08_lead_time_analysis", "09_simulate_intervention",
                  "10_build_report"):
        lines.append(f"| {stage} | {status_of(stage)} |")
    lines.append("")
    out = Path("docs") / ("RESULTS_SMOKE.md" if cfg.data.synthetic else "RESULTS.md")
    atomic_write_text(out, "\n".join(lines) + "\n")
    summary = [f"Wrote {out}.", f"Curve rows: {len(curve) if curve is not None else 'NOT_RUN'}.",
               f"Probe heatmap: {'NOT_RUN' if heat is None or heat.empty else f'{len(heat)} cells'}."]
    log.info("report written to %s", out)
    manifest.log("10_build_report", args.config, "OK", {"report": str(out)})
    print_summary_block("10_build_report", summary)


if __name__ == "__main__":
    main()
