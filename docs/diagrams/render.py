"""
WHAT: Renders the TikZ diagrams in docs/diagrams/ to vector PDF (+ PNG preview).

WHY:  Brief §6: diagrams are kept as TikZ source (vector, fonts match the
      paper) and must also exist as rendered PDFs. The README needs a PNG
      because GitHub cannot display PDFs inline. Rendering by script keeps the
      diagrams regenerable with one command (`make diagrams`).

HOW:  Each diagram's `tikzpicture` is wrapped in a `standalone` document and
      compiled with Tectonic. A fourth diagram - a worked example drawn from a
      REAL ProcessBench trace - is generated first from
      data/processed/processed_traces.jsonl using a fixed selection rule, so
      the example is data, not an invented illustration.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = HERE / "rendered"

PREAMBLE = r"""\documentclass[tikz,border=4pt]{standalone}
\usepackage{amsmath,amssymb,pifont}
\usetikzlibrary{arrows.meta,positioning,shapes.geometric,calc,fit,backgrounds}
\begin{document}
"""


def extract_tikzpicture(tex: str) -> str:
    """Return the first tikzpicture environment (drops figure/caption wrappers)."""
    match = re.search(r"\\begin\{tikzpicture\}.*?\\end\{tikzpicture\}", tex, flags=re.S)
    if not match:
        raise ValueError("no tikzpicture environment found")
    return match.group(0)


def latex_escape(text: str) -> str:
    """Escape LaTeX special characters in dataset text (math is shown verbatim, not typeset)."""
    replacements = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&",
                    "#": r"\#", "_": r"\_", "%": r"\%", "^": r"\^{}", "~": r"\~{}"}
    return "".join(replacements.get(ch, ch) for ch in text)


def select_real_example(processed_path: Path) -> dict | None:
    """Fixed rule: GSM8K-tier ProcessBench trace, wrong final answer, 4-6 steps,
    first error strictly inside the chain (1 < e < n), shortest longest-step; ties by trace_id."""
    if not processed_path.exists():
        return None
    candidates = []
    for line in processed_path.read_text(encoding="utf-8").splitlines():
        row = json.loads(line)
        n, e = row["n_steps"], row["first_error_idx"]
        if (row["subset"] == "gsm8k" and row["answer_incorrect"] and e is not None
                and 4 <= n <= 6 and 1 < e < n):
            candidates.append((max(len(s) for s in row["steps"]), row["trace_id"], row))
    if not candidates:
        return None
    return sorted(candidates, key=lambda c: (c[0], c[1]))[0][2]


def real_example_tikz(row: dict, max_chars: int = 150) -> str:
    """TikZ source for the real worked example with the choke point annotated."""
    e, n = int(row["first_error_idx"]), int(row["n_steps"])  # JSON may hold 2.0; print integers
    lines = [
        "% AUTO-GENERATED by docs/diagrams/render.py from data/processed/processed_traces.jsonl.",
        f"% ProcessBench trace {row['trace_id']} (generator: {row['generator']}). Do not edit by hand.",
        r"\begin{tikzpicture}[font=\sffamily\scriptsize, >={Stealth[length=2mm]},",
        r"  tracestep/.style={rectangle, rounded corners=1.5pt, draw=black!60, align=left,",
        r"               text width=12.5cm, inner sep=2mm},",
        r"  okstep/.style={tracestep, fill=green!7}, badstep/.style={tracestep, fill=red!10, draw=red!70!black, line width=0.8pt},",
        r"  afterstep/.style={tracestep, fill=gray!8, draw=black!35, dashed}]",
    ]
    question = latex_escape(row["question"][:max_chars * 2] + ("..." if len(row["question"]) > max_chars * 2 else ""))
    lines.append(rf"\node[tracestep, fill=blue!5] (q) at (0,0) {{\textbf{{Question}} ({latex_escape(row['subset'])} tier): {question}}};")
    previous = "q"
    for k, text in enumerate(row["steps"], start=1):
        style = "okstep" if k < e else ("badstep" if k == e else "afterstep")
        body = latex_escape(text[:max_chars] + ("..." if len(text) > max_chars else ""))
        tag = rf"\textbf{{$s_{{{k}}}$}}"
        if k == e:
            tag += rf" \textcolor{{red!70!black}}{{\textbf{{first error: $e={e}$, $\rho=e/n={e / n:.2f}$}}}}"
        elif k > e:
            tag += r" \textit{(after the error)}"
        lines.append(rf"\node[{style}, below=2.5mm of {previous}] (s{k}) {{{tag}: {body}}};")
        lines.append(rf"\draw[->] ({previous}.south) -- (s{k}.north);")
        previous = f"s{k}"
    lines.append(rf"\node[tracestep, fill=black!6, below=2.5mm of {previous}] (a) {{\textbf{{Outcome}}: final answer "
                 rf"incorrect ($y=1$); $n={n}$ steps, {n - e} step(s) remain after the first error.}};")
    lines.append(rf"\draw[->] ({previous}.south) -- (a.north);")
    lines.append(r"\end{tikzpicture}")
    return "\n".join(lines) + "\n"


def compile_standalone(name: str, tikz: str, tectonic: str) -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    source = OUT / f"{name}.tex"
    source.write_text(PREAMBLE + tikz + "\n\\end{document}\n", encoding="utf-8")
    subprocess.run([tectonic, "--outdir", str(OUT), str(source)], check=True,
                   capture_output=True, text=True)
    return OUT / f"{name}.pdf"


def pdf_to_png(pdf: Path, dpi: int = 200) -> Path:
    import pymupdf

    with pymupdf.open(pdf) as document:
        png = pdf.with_suffix(".png")
        document[0].get_pixmap(dpi=dpi).save(png)
    return png


def main() -> None:
    parser = argparse.ArgumentParser(description="Render TikZ diagrams to PDF + PNG")
    parser.add_argument("--tectonic", default="tectonic")
    args = parser.parse_args()

    example = select_real_example(ROOT / "data" / "processed" / "processed_traces.jsonl")
    if example is not None:
        (HERE / "worked_example_processbench.tex").write_text(real_example_tikz(example), encoding="utf-8")
    else:
        print("worked_example_processbench: NOT_RUN (run make preprocess first)")

    written = []
    for name in ("architecture", "pipeline", "worked_example", "worked_example_processbench"):
        path = HERE / f"{name}.tex"
        if not path.exists():
            continue
        try:
            pdf = compile_standalone(name, extract_tikzpicture(path.read_text(encoding="utf-8")),
                                     args.tectonic)
        except subprocess.CalledProcessError as exc:
            print(f"{name}: LaTeX FAILED\n{exc.stdout[-2000:]}\n{exc.stderr[-2000:]}")
            sys.exit(1)
        written += [pdf, pdf_to_png(pdf)]
        (OUT / f"{name}.tex").unlink()  # the wrapper is reproducible; keep only outputs
    for path in written:
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
